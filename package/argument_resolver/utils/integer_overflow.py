_DEFAULT_OP_NAMES = ("Add", "Sub", "Mul", "Shl")
_DEFAULT_BIT_WIDTHS = (8, 16, 32, 64)
_CAST_OP_RE = re.compile(r"Iop_(\d+)([SU]?)to(\d+)")


def _normalize_op_name(name: str) -> str:
    """
    Normalize user-provided operation names such as "iop_add32" into "Add".
    """

    stripped = name.strip()
    if stripped.lower().startswith("iop_"):
        stripped = stripped[4:]
    elif stripped.lower().startswith("iop"):
        stripped = stripped[3:]

    # Drop trailing digits that encode bit-width.
    while stripped and stripped[-1].isdigit():
        stripped = stripped[:-1]

    if not stripped:
        raise ValueError(f"Invalid VEX op name: {name!r}")

    return stripped[0].upper() + stripped[1:].lower()


def _default_bit_widths(project: angr.Project) -> Tuple[int, ...]:
    """
    Return the set of bit-widths to inspect when the caller does not constrain
    them.  By default we cover the common VEX sizes (8/16/32/64) but cap the
    maximum to the architecture width so we do not generate impossible op names.
    """

    arch_bits = getattr(project.arch, "bits", 0) or 0
    if arch_bits == 0:
        return _DEFAULT_BIT_WIDTHS

    valid = tuple(sorted({bits for bits in _DEFAULT_BIT_WIDTHS if bits <= arch_bits}))
    return valid or _DEFAULT_BIT_WIDTHS


def _parse_int(value: str) -> int:
    value = value.strip()
    return int(value, 16) if value.startswith("0x") or value.startswith("0X") else int(value)


@dataclass(frozen=True)
class OperandWidthState:
    width: Optional[int]
    source_width: Optional[int]
    signed: Optional[bool]
    origin: str
    # Inclusive unsigned bit-pattern bounds. None denotes the full width.
    unsigned_bounds: Optional[Tuple[int, int]] = None


@dataclass(frozen=True)
class FollowupWiden:
    dst_width: int
    signed: Optional[bool]


@dataclass(frozen=True)
class ArithmeticOperation:
    function: str
    function_addr: int
    block_addr: int
    stmt_idx: int
    tmp: int
    vex_op: str
    bit_width: int
    operand0: str
    operand1: str
    ins_addr: Optional[int]
    classification: Optional[str] = None
    notes: Dict[str, bool] = field(default_factory=dict)
    operand_states: Tuple[OperandWidthState, ...] = field(default_factory=tuple)
    widen_uses: Tuple[FollowupWiden, ...] = field(default_factory=tuple)
    narrow_use_width: Optional[int] = None

    def code_location(self) -> CodeLocation:
        """
        Build an angr ``CodeLocation`` for later RDA lookups.
        """

        return CodeLocation(block_addr=self.block_addr, stmt_idx=self.stmt_idx, ins_addr=self.ins_addr)

    def as_dict(self) -> Dict:
        data = asdict(self)
        if self.ins_addr is not None:
            data["ins_addr"] = hex(self.ins_addr)
        data["function_addr"] = hex(self.function_addr)
        data["block_addr"] = hex(self.block_addr)
        data["stmt_idx"] = self.stmt_idx
        data["tmp"] = self.tmp
        return data


@dataclass
class UsageSite:
    stmt_idx: int
    kind: str
    target_reg: Optional[int] = None
    produced_tmp: Optional[int] = None


@dataclass
class RegUsage:
    stmt_idx: int
    kind: str
    target_reg: Optional[int] = None
    produced_tmp: Optional[int] = None
    read_width: Optional[int] = None


@dataclass
class ExprContext:
    kind: str
    stmt_idx: int
    produced_tmp: Optional[int] = None
    target_reg: Optional[int] = None


class IRSBUseDef:
    """
    Build tmp/reg def-use information for a given IRSB and expose arithmetic candidates.
    """

    def __init__(self, block: angr.block.Block, arch):
        self.block = block
        self.arch = arch
        self.def_tmp: Dict[int, int] = {}
        self._width_cache: Dict[Tuple[int, int], OperandWidthState] = {}
        self.uses_tmp: Dict[int, List[UsageSite]] = defaultdict(list)
        self.uses_reg: Dict[int, List[RegUsage]] = defaultdict(list)
        self.arith_nodes: List[Tuple[int, str, int, Optional[int]]] = []
        self.pointerish_tmps: Set[int] = set()
        self.frame_pointer_offsets: Set[int] = self._collect_frame_pointer_offsets()
        self.tyenv = self.block.vex.tyenv

        self.sp_offset = getattr(self.arch, "sp_offset", None)
        self.pc_offset = getattr(self.arch, "ip_offset", None)
        self.lr_offset = getattr(self.arch, "lr_offset", None)
        self.return_offsets = self._collect_return_offsets()

        self._build()

    def _build(self) -> None:
        irsb = self.block.vex
        current_insn = self.block.addr
        for idx, stmt in enumerate(irsb.statements):
            if isinstance(stmt, pyvex.IRStmt.IMark):
                current_insn = stmt.addr
                continue
            if isinstance(stmt, pyvex.IRStmt.WrTmp):
                self.def_tmp[stmt.tmp] = idx
                expr = stmt.data
                arith_op = self._arith_op(expr)
                ctx_kind = "arith" if arith_op else "tmp_assign"
                self._handle_expr(expr, ExprContext(ctx_kind, idx, produced_tmp=stmt.tmp))
                if arith_op:
                    if self._looks_like_pointer_expr(expr, current_insn):
                        self.pointerish_tmps.add(stmt.tmp)
                    self.arith_nodes.append((stmt.tmp, arith_op, idx, current_insn))
            elif isinstance(stmt, pyvex.IRStmt.Put):
                self._handle_expr(stmt.data, ExprContext("put_reg", idx, target_reg=stmt.offset))
            elif isinstance(stmt, pyvex.IRStmt.Store):
                self._handle_expr(stmt.addr, ExprContext("store_addr", idx))
                self._handle_expr(stmt.data, ExprContext("store_value", idx))
            elif isinstance(stmt, pyvex.IRStmt.LoadG):
                self._handle_expr(stmt.addr, ExprContext("load_addr", idx))
                self._handle_expr(stmt.alt, ExprContext("tmp_assign", idx))
                self._handle_expr(stmt.guard, ExprContext("cmp", idx))
            elif isinstance(stmt, pyvex.IRStmt.StoreG):
                self._handle_expr(stmt.addr, ExprContext("store_addr", idx))
                self._handle_expr(stmt.data, ExprContext("store_value", idx))
                self._handle_expr(stmt.guard, ExprContext("cmp", idx))
            elif isinstance(stmt, pyvex.IRStmt.Exit):
                self._handle_expr(stmt.guard, ExprContext("exit_cond", idx))
            elif isinstance(stmt, pyvex.IRStmt.Dirty):
                for tmp in stmt.tmp_list or []:
                    self.def_tmp[tmp] = idx
                for expr in stmt.args:
                    self._handle_expr(expr, ExprContext("tmp_assign", idx))
                if stmt.guard is not None:
                    self._handle_expr(stmt.guard, ExprContext("cmp", idx))

        if isinstance(irsb.next, pyvex.IRExpr.IRExpr):
            self._handle_expr(irsb.next, ExprContext("next", len(irsb.statements)))

    @staticmethod
    def _arith_op(expr) -> Optional[str]:
        if isinstance(expr, pyvex.IRExpr.Binop):
            op = expr.op
            if any(op.startswith(prefix) for prefix in ("Iop_Add", "Iop_Sub", "Iop_Mul", "Iop_Shl")):
                return op
        if isinstance(expr, pyvex.IRExpr.Unop):
            op = expr.op
            if "Shl" in op:
                return op
        return None

    def _handle_expr(self, expr, ctx: ExprContext):
        if expr is None:
            return
        if isinstance(expr, pyvex.IRExpr.RdTmp):
            self.uses_tmp[expr.tmp].append(
                UsageSite(ctx.stmt_idx, ctx.kind, ctx.target_reg, ctx.produced_tmp)
            )
            if ctx.produced_tmp is not None and self._is_pointerish_tmp(expr.tmp):
                self.pointerish_tmps.add(ctx.produced_tmp)
            return
        if isinstance(expr, pyvex.IRExpr.Get):
            self.uses_reg[expr.offset].append(
                RegUsage(ctx.stmt_idx, ctx.kind, ctx.target_reg, ctx.produced_tmp, self._expr_result_bits(expr))
            )
            if ctx.produced_tmp is not None and self._is_sp(expr.offset):
                self.pointerish_tmps.add(ctx.produced_tmp)
            if ctx.produced_tmp is not None and expr.offset in self.frame_pointer_offsets:
                self.pointerish_tmps.add(ctx.produced_tmp)
            return
        if isinstance(expr, pyvex.IRExpr.Load):
            # The address is consumed by the load; it does not define the type
            # of the loaded value (e.g. an integer parameter in a stack slot).
            self._handle_expr(expr.addr, ExprContext("load_addr", ctx.stmt_idx))
            return
        if isinstance(expr, pyvex.IRExpr.Unop):
            self._handle_expr(expr.args[0], ctx)
            return
        if isinstance(expr, pyvex.IRExpr.Binop):
            for arg in expr.args:
                self._handle_expr(arg, ctx)
            return
        if isinstance(expr, pyvex.IRExpr.Triop):
            for arg in expr.args:
                self._handle_expr(arg, ctx)
            return
        if isinstance(expr, pyvex.IRExpr.Qop):
            for arg in expr.args:
                self._handle_expr(arg, ctx)
            return
        if isinstance(expr, pyvex.IRExpr.ITE):
            self._handle_expr(expr.cond, ExprContext("cmp", ctx.stmt_idx, ctx.produced_tmp, ctx.target_reg))
            self._handle_expr(expr.iftrue, ctx)
            self._handle_expr(expr.iffalse, ctx)
            return
        if isinstance(expr, pyvex.IRExpr.CCall):
            for arg in expr.args:
                self._handle_expr(arg, ctx)
            return
        # Const, Vector, etc. carry no further uses

    def classify_tmp(self, tmp_id: int) -> Tuple[str, Dict[str, bool]]:
        flags = {
            "used_as_addr": False,
            "used_as_store_value": False,
            "updates_sp": False,
            "updates_pc": False,
            "escapes_as_value": False,
            "in_conditional_only": False,
            "looks_like_addr": False,
        }
        cond_seen = False
        non_cond_seen = False
        worklist: Deque[Tuple[str, int, bool]] = deque()
        visited: Set[Tuple[str, int, bool]] = set()
        worklist.append(("tmp", tmp_id, self._is_pointerish_tmp(tmp_id)))

        while worklist:
            kind, ident, is_pointer = worklist.pop()
            if (kind, ident, is_pointer) in visited:
                continue
            visited.add((kind, ident, is_pointer))

            if is_pointer:
                flags["looks_like_addr"] = True

            if kind == "tmp":
                uses = self.uses_tmp.get(ident, [])
                for use in uses:
                    if use.kind == "put_reg":
                        non_cond_seen = True
                        target = use.target_reg
                        if target is None:
                            continue
                        if self._is_sp(target):
                            flags["updates_sp"] = True
                        elif self._is_pc_like(target):
                            flags["updates_pc"] = True
                        elif self._is_return_reg(target):
                            if not (is_pointer or flags["used_as_addr"] or flags["looks_like_addr"]):
                                flags["escapes_as_value"] = True
                        else:
                            worklist.append(("reg", target, is_pointer))
                    elif use.kind in ("store_addr", "load_addr"):
                        non_cond_seen = True
                        flags["used_as_addr"] = True
                    elif use.kind == "store_value":
                        non_cond_seen = True
                        flags["used_as_store_value"] = True
                        flags["escapes_as_value"] = True
                    elif use.kind in ("arith", "tmp_assign"):
                        non_cond_seen = True
                        if use.produced_tmp is not None:
                            next_pointer = is_pointer or self._is_pointerish_tmp(use.produced_tmp)
                            worklist.append(("tmp", use.produced_tmp, next_pointer))
                    elif use.kind == "next":
                        non_cond_seen = True
                        flags["updates_pc"] = True
                    elif use.kind in ("exit_cond", "cmp"):
                        cond_seen = True
                    elif use.kind == "call_arg":
                        non_cond_seen = True
                        if not (is_pointer or flags["used_as_addr"] or flags["looks_like_addr"]):
                            flags["escapes_as_value"] = True
            elif kind == "reg":
                uses = self.uses_reg.get(ident, [])
                has_effect = False
                for use in uses:
                    if use.kind not in ("exit_cond", "cmp"):
                        has_effect = True
                    if use.kind in ("arith", "tmp_assign") and use.produced_tmp is not None:
                        non_cond_seen = True
                        next_pointer = is_pointer or self._is_pointerish_tmp(use.produced_tmp)
                        worklist.append(("tmp", use.produced_tmp, next_pointer))
                    elif use.kind in ("store_addr", "load_addr"):
                        non_cond_seen = True
                        flags["used_as_addr"] = True
                    elif use.kind == "store_value":
                        non_cond_seen = True
                        flags["used_as_store_value"] = True
                        flags["escapes_as_value"] = True
                    elif use.kind == "put_reg":
                        non_cond_seen = True
                        target = use.target_reg
                        if target is None:
                            continue
                        if self._is_sp(target):
                            flags["updates_sp"] = True
                        elif self._is_pc_like(target):
                            flags["updates_pc"] = True
                        elif self._is_return_reg(target):
                            if not (is_pointer or flags["used_as_addr"] or flags["looks_like_addr"]):
                                flags["escapes_as_value"] = True
                        else:
                            worklist.append(("reg", target, is_pointer))
                    elif use.kind == "call_arg":
                        non_cond_seen = True
                        if not (is_pointer or flags["used_as_addr"] or flags["looks_like_addr"]):
                            flags["escapes_as_value"] = True
                    elif use.kind == "exit_cond":
                        cond_seen = True
                if has_effect:
                    pass

        flags["in_conditional_only"] = cond_seen and not non_cond_seen

        classification = self._class_from_flags(flags)
        return classification, flags

    def _class_from_flags(self, flags: Dict[str, bool]) -> str:
        if flags["updates_pc"]:
            return "control_flow"
        if flags["updates_sp"]:
            return "stack_update"
        if flags["used_as_store_value"]:
            return "value_arith"
        if flags["used_as_addr"] or flags["looks_like_addr"]:
            return "pointer_arith"
        if flags["escapes_as_value"] and not (
            flags["used_as_addr"] or flags["looks_like_addr"] or flags["updates_sp"] or flags["updates_pc"]
        ):
            return "value_arith"
        return "flag_only_or_other"

    def _is_sp(self, reg_offset: int) -> bool:
        return self.sp_offset is not None and reg_offset == self.sp_offset

    def _is_pc_like(self, reg_offset: int) -> bool:
        if self.pc_offset is not None and reg_offset == self.pc_offset:
            return True
        if self.lr_offset is not None and reg_offset == self.lr_offset:
            return True
        return False

    def _is_return_reg(self, reg_offset: int) -> bool:
        return reg_offset in self.return_offsets

    def _collect_return_offsets(self) -> Set[int]:
        offsets: Set[int] = set()
        candidates = []
        for attr in (
            "return_register",
            "return_registers",
            "default_return_register",
            "default_return_registers",
        ):
            reg = getattr(self.arch, attr, None)
            if reg:
                candidates.extend(self._flatten_register_descriptor(reg))
        ret_offset = getattr(self.arch, "ret_offset", None)
        if isinstance(ret_offset, int):
            offsets.add(ret_offset)
        for reg in candidates:
            resolved = self._resolve_reg_offset(reg)
            if resolved is not None:
                offsets.add(resolved)
        return offsets

    def _flatten_register_descriptor(self, desc):
        if desc is None:
            return []
        if isinstance(desc, (list, tuple, set)):
            out = []
            for item in desc:
                out.extend(self._flatten_register_descriptor(item))
            return out
        return [desc]

    def _resolve_reg_offset(self, reg) -> Optional[int]:
        if isinstance(reg, int):
            return reg
        if isinstance(reg, str):
            info = self.arch.registers.get(reg)
            if info:
                return info[0]
            return None
        for attr in ("vex_offset", "reg_offset", "offset"):
            if hasattr(reg, attr):
                try:
                    value = getattr(reg, attr)
                except Exception:
                    continue
                if isinstance(value, int):
                    return value
        return None

    def _is_pointerish_tmp(self, tmp_id: int) -> bool:
        return tmp_id in self.pointerish_tmps

    def _looks_like_pointer_expr(self, expr, ins_addr: Optional[int]) -> bool:
        if not isinstance(expr, pyvex.IRExpr.Binop):
            return False
        if not expr.op.startswith(("Iop_Add", "Iop_Sub")):
            return False
        for arg in expr.args:
            if self._expr_reads_pc(arg):
                return True
            if self._expr_depends_on_pointer_tmp(arg):
                return True
            if self._expr_is_code_const(arg, ins_addr):
                return True
        left, right = expr.args
        if self._expr_reads_sp(left) and self._is_const_expr(right):
            return True
        if self._expr_reads_sp(right) and self._is_const_expr(left):
            return True
        if self._expr_reads_frame_pointer(left) and self._is_const_expr(right):
            return True
        if self._expr_reads_frame_pointer(right) and self._is_const_expr(left):
            return True
        return False

    def _expr_reads_pc(self, expr) -> bool:
        if isinstance(expr, pyvex.IRExpr.Get):
            return self.pc_offset is not None and expr.offset == self.pc_offset
        if isinstance(expr, pyvex.IRExpr.RdTmp):
            return False
        if isinstance(expr, pyvex.IRExpr.Const):
            return False
        if hasattr(expr, "args"):
            return any(self._expr_reads_pc(arg) for arg in expr.args)
        if isinstance(expr, pyvex.IRExpr.Load):
            return self._expr_reads_pc(expr.addr)
        return False

    def _expr_reads_sp(self, expr) -> bool:
        if self.sp_offset is None:
            return False
        if isinstance(expr, pyvex.IRExpr.Get):
            return expr.offset == self.sp_offset
        if hasattr(expr, "args"):
            return any(self._expr_reads_sp(arg) for arg in expr.args)
        if isinstance(expr, pyvex.IRExpr.Load):
            return self._expr_reads_sp(expr.addr)
        return False

    def _expr_reads_frame_pointer(self, expr) -> bool:
        if not self.frame_pointer_offsets:
            return False
        if isinstance(expr, pyvex.IRExpr.Get):
            return expr.offset in self.frame_pointer_offsets
        if hasattr(expr, "args"):
            return any(self._expr_reads_frame_pointer(arg) for arg in expr.args)
        if isinstance(expr, pyvex.IRExpr.Load):
            return self._expr_reads_frame_pointer(expr.addr)
        return False

    @staticmethod
    def _is_const_expr(expr) -> bool:
        return isinstance(expr, pyvex.IRExpr.Const)

    def _expr_depends_on_pointer_tmp(self, expr) -> bool:
        if isinstance(expr, pyvex.IRExpr.RdTmp):
            return expr.tmp in self.pointerish_tmps
        if hasattr(expr, "args"):
            return any(self._expr_depends_on_pointer_tmp(arg) for arg in expr.args)
        if isinstance(expr, pyvex.IRExpr.Load):
            return self._expr_depends_on_pointer_tmp(expr.addr)
        return False

    @staticmethod
    def _expr_is_code_const(expr, ins_addr: Optional[int]) -> bool:
        if not isinstance(expr, pyvex.IRExpr.Const):
            return False
        if ins_addr is None:
            return False
        value = expr.con.value
        return abs(value - ins_addr) <= 0x1000

    def _is_return_reg(self, reg_offset: int) -> bool:
        return reg_offset in self.return_offsets

    def _collect_return_offsets(self) -> Set[int]:
        offsets: Set[int] = set()
        candidates = []
        for attr in (
            "return_register",
            "return_registers",
            "default_return_register",
            "default_return_registers",
        ):
            reg = getattr(self.arch, attr, None)
            if reg:
                candidates.extend(self._flatten_register_descriptor(reg))
        ret_offset = getattr(self.arch, "ret_offset", None)
        if isinstance(ret_offset, int):
            offsets.add(ret_offset)
        for reg in candidates:
            off = self._resolve_reg_offset(reg)
            if off is not None:
                offsets.add(off)
        return offsets

    def _collect_frame_pointer_offsets(self) -> Set[int]:
        offsets: Set[int] = set()
        for attr in ("fp_offset", "bp_offset"):
            value = getattr(self.arch, attr, None)
            if isinstance(value, int):
                offsets.add(value)
        candidate_names = ("bp", "rbp", "ebp", "fp", "r11", "x29")
        for name in candidate_names:
            reg = self.arch.registers.get(name)
            if reg:
                offsets.add(reg[0])
        return offsets

    def _flatten_register_descriptor(self, desc):
        if desc is None:
            return []
        if isinstance(desc, (list, tuple, set)):
            out = []
            for item in desc:
                out.extend(self._flatten_register_descriptor(item))
            return out
        return [desc]

    def _resolve_reg_offset(self, reg) -> Optional[int]:
        if isinstance(reg, int):
            return reg
        if isinstance(reg, str):
            info = self.arch.registers.get(reg)
            if info:
                return info[0]
            return None
        for attr in ("vex_offset", "reg_offset", "offset"):
            if hasattr(reg, attr):
                try:
                    value = getattr(reg, attr)
                except Exception:
                    continue
                if isinstance(value, int):
                    return value
        return None

    def operand_width_states(self, stmt_idx: int) -> Tuple[OperandWidthState, ...]:
        stmt = self.block.vex.statements[stmt_idx]
        data = stmt.data
        if isinstance(data, pyvex.IRExpr.Binop):
            exprs = data.args[:2]
        elif isinstance(data, pyvex.IRExpr.Unop):
            exprs = (data.args[0],)
        else:
            exprs = ()
        return tuple(self._operand_width_state(expr, 10) for expr in exprs)

    def followup_widens(self, tmp_id: int) -> Tuple[FollowupWiden, ...]:
        uses = self.uses_tmp.get(tmp_id, [])
        widens: List[FollowupWiden] = []
        statements = self.block.vex.statements
        for use in uses:
            # IRSB.next uses an index after the last statement; it is not a WrTmp.
            if not 0 <= use.stmt_idx < len(statements):
                continue
            stmt = statements[use.stmt_idx]
            if not isinstance(stmt, pyvex.IRStmt.WrTmp):
                continue
            data = stmt.data
            if not isinstance(data, pyvex.IRExpr.Unop):
                continue
            if not data.args:
                continue
            arg = data.args[0]
            if not isinstance(arg, pyvex.IRExpr.RdTmp) or arg.tmp != tmp_id:
                continue
            match = self._match_widen_op(data)
            if not match:
                continue
            _, signed, dst_bits = match
            widens.append(FollowupWiden(dst_width=dst_bits, signed=signed))
        return tuple(widens)

    def _later_register_reads(self, write_idx: int) -> Iterator[RegUsage]:
        put = self.block.vex.statements[write_idx]
        if not isinstance(put.data, pyvex.IRExpr.RdTmp):
            return
        width = self._expr_result_bits(put.data)
        if not width:
            return
        # Include later overlapping subregisters. An intervening overwrite
        # can only make this guard keep an extra candidate.
        for offset in range(put.offset, put.offset + (width + 7) // 8):
            for read in self.uses_reg.get(offset, ()):
                if read.stmt_idx > write_idx:
                    yield read

    def narrow_use_width(self, tmp_id: int) -> Optional[int]:
        """Find the narrowest local value use through copies and integer casts."""
        minimum = None
        work = [tmp_id]
        visited = set()
        while work:
            tmp = work.pop()
            if tmp in visited:
                continue
            visited.add(tmp)
            for use in self.uses_tmp.get(tmp, ()):
                # A subregister read can narrow a value without an IR cast.
                if use.kind == "put_reg":
                    for read in self._later_register_reads(use.stmt_idx):
                        if read.read_width:
                            minimum = min(minimum or read.read_width, read.read_width)
                        if read.produced_tmp is not None:
                            data = self.block.vex.statements[read.stmt_idx].data
                            if isinstance(data, pyvex.IRExpr.Get):
                                work.append(read.produced_tmp)
                if use.produced_tmp is None:
                    continue
                data = self.block.vex.statements[use.stmt_idx].data
                if isinstance(data, pyvex.IRExpr.RdTmp):
                    work.append(use.produced_tmp)
                    continue
                cast = self._match_cast_op(data)
                if cast and isinstance(data.args[0], pyvex.IRExpr.RdTmp) and data.args[0].tmp == tmp:
                    src, _, dst = cast
                    if dst < src:
                        minimum = dst if minimum is None else min(minimum, dst)
                    work.append(use.produced_tmp)
        return minimum

    def _operand_width_state(self, expr, budget: int) -> OperandWidthState:
        width = self._expr_result_bits(expr)
        if not width or budget <= 0:
            return OperandWidthState(width, None, None, "unknown")
        if isinstance(expr, pyvex.IRExpr.RdTmp):
            key = (expr.tmp, budget)
            if key not in self._width_cache:
                idx = self.def_tmp.get(expr.tmp)
                stmt = self.block.vex.statements[idx] if idx is not None else None
                if isinstance(stmt, pyvex.IRStmt.WrTmp):
                    state = self._operand_width_state(stmt.data, budget - 1)
                else:
                    state = OperandWidthState(width, None, None, "unknown")
                self._width_cache[key] = state
            return self._width_cache[key]
        if isinstance(expr, pyvex.IRExpr.Const):
            value = expr.con.value
            return OperandWidthState(width, None, None, "const", (value, value))
        if isinstance(expr, pyvex.IRExpr.Get):
            return OperandWidthState(width, None, None, "register")
        if isinstance(expr, pyvex.IRExpr.Load):
            return OperandWidthState(width, None, None, "memory")
        cast = self._match_cast_op(expr)
        if cast:
            src, signed, dst = cast
            source = self._operand_width_state(expr.args[0], budget - 1)
            lo, hi = source.unsigned_bounds or (0, (1 << src) - 1)
            if dst < src:
                # A single interval survives truncation only within one modulus band.
                mask = (1 << dst) - 1
                bounds = (lo & mask, hi & mask) if lo >> dst == hi >> dst else None
                return OperandWidthState(dst, src, signed, "trunc", bounds)
            if dst > src and signed is not None:
                bounds = (lo, hi)
                if signed and hi >= (1 << (src - 1)):
                    offset = (1 << dst) - (1 << src)
                    bounds = (lo + offset, hi + offset) if lo >= (1 << (src - 1)) else None
                return OperandWidthState(dst, src, signed, "widen", bounds)
        if isinstance(expr, pyvex.IRExpr.Binop) and expr.op == f"Iop_And{width}":
            for arg in expr.args:
                if isinstance(arg, pyvex.IRExpr.Const):
                    return OperandWidthState(width, None, None, "mask", (0, arg.con.value))
        if isinstance(expr, pyvex.IRExpr.Binop) and expr.op == f"Iop_Shr{width}":
            value, count = expr.args
            if isinstance(count, pyvex.IRExpr.Const) and 0 <= count.con.value < width:
                shift = count.con.value
                source = self._operand_width_state(value, budget - 1)
                lo, hi = source.unsigned_bounds or (0, (1 << width) - 1)
                return OperandWidthState(width, None, None, "computed", (lo >> shift, hi >> shift))
        if isinstance(expr, pyvex.IRExpr.ITE):
            first = self._operand_width_state(expr.iftrue, budget - 1).unsigned_bounds
            if first is not None:
                second = self._operand_width_state(expr.iffalse, budget - 1).unsigned_bounds
                if second is not None:
                    bounds = min(first[0], second[0]), max(first[1], second[1])
                    return OperandWidthState(width, None, None, "computed", bounds)
        return OperandWidthState(width, None, None, "computed")

    def _expr_result_bits(self, expr) -> Optional[int]:
        if expr is None:
            return None
        if hasattr(expr, "result_size"):
            try:
                size = expr.result_size(self.tyenv)
            except TypeError:
                size = None
            if size:
                return int(size)
        return None

    def _match_cast_op(self, expr) -> Optional[Tuple[int, Optional[bool], int]]:
        op = getattr(expr, "op", None)
        if not op:
            return None
        match = _CAST_OP_RE.fullmatch(op)
        if not match:
            return None
        src_bits = int(match.group(1))
        signed = match.group(2)
        dst_bits = int(match.group(3))
        if signed == "S":
            signed_flag: Optional[bool] = True
        elif signed == "U":
            signed_flag = False
        else:
            signed_flag = None
        return src_bits, signed_flag, dst_bits

    def _match_widen_op(self, expr) -> Optional[Tuple[int, Optional[bool], int]]:
        match = self._match_cast_op(expr)
        if not match:
            return None
        src_bits, signed, dst_bits = match
        if src_bits >= dst_bits:
            return None
        return src_bits, signed, dst_bits


class IntegerOverflowScanner:
    """
    Scan every IRSB in the binary and harvest arithmetic ``WrTmp`` statements.
    """

    def __init__(
        self,
        project: angr.Project,
        *,
        bit_widths: Optional[Iterable[int]] = None,
        op_names: Optional[Iterable[str]] = None,
        logger: Optional[logging.Logger] = None,
    ):
        self.project = project
        self.loop_counter_skips = 0
        self.logger = logger or logging.getLogger(__name__)
        self.bit_widths: Set[int] = set(bit_widths or _default_bit_widths(project))
        self.base_ops: Set[str] = { _normalize_op_name(op) for op in (op_names or _DEFAULT_OP_NAMES) }
        self.target_ops: Set[str] = {
            f"Iop_{base}{bits}" for base in self.base_ops for bits in self.bit_widths
        }

    def scan(
        self,
        *,
        function_names: Optional[Sequence[str]] = None,
        function_addrs: Optional[Sequence[int]] = None,
        min_addr: Optional[int] = None,
        max_addr: Optional[int] = None,
        value_sinks_only: bool = False,
    ) -> List[ArithmeticOperation]:
        """
        Collect matching arithmetic statements. In detection mode, build metadata
        only for value arithmetic with an instruction address.
        """

        allowed_funcs = self._resolve_function_filter(function_names, function_addrs)
        operations: List[ArithmeticOperation] = []
        seen: Set[Tuple[int, int, int]] = set()
        self.loop_counter_skips = 0

        for func in self._iter_functions(allowed_funcs):
            loops = LoopBranches(func) if value_sinks_only else None
            for block in self._iter_blocks(func):
                operations.extend(self._scan_block(func, block, min_addr=min_addr, max_addr=max_addr,
                                                   value_sinks_only=value_sinks_only, seen=seen, loops=loops))
        if value_sinks_only:
            self.logger.info("Scanner discovered %d arithmetic sinks (%d value_arith)",
                             len(seen), len(operations) + self.loop_counter_skips)
            self.logger.info("Loop-counter heuristic skipped %d value sinks", self.loop_counter_skips)
        return operations

    def _resolve_function_filter(
        self,
        function_names: Optional[Sequence[str]],
        function_addrs: Optional[Sequence[int]],
    ) -> Optional[Set[int]]:
        addrs: Set[int] = set(function_addrs or [])
        if function_names:
            for name in function_names:
                func = self.project.kb.functions.function(name=name)
                if func is None:
                    self.logger.warning("Function %s not found; skipping filter", name)
                    continue
                addrs.add(func.addr)
        return addrs or None

    def _iter_functions(self, allowed_addrs: Optional[Set[int]]) -> Iterator[Function]:
        functions = self.project.kb.functions.values()
        for func in functions:
            if func.is_plt or func.is_syscall or func.is_simprocedure:
                continue
            if allowed_addrs is not None and func.addr not in allowed_addrs:
                continue
            yield func

    def _iter_blocks(self, func) -> Iterator[angr.block.Block]:
        try:
            blocks = list(func.blocks)
        except angr_errors.SimTranslationError:
            self.logger.debug("Failed to translate blocks for %s", func.name)
            return
        seen = set()
        for block in blocks:
            if block.addr in seen:
                continue
            seen.add(block.addr)
            yield block

    def _scan_block(
        self,
        func,
        block: angr.block.Block,
        *,
        min_addr: Optional[int],
        max_addr: Optional[int],
        value_sinks_only: bool = False,
        seen: Optional[Set[Tuple[int, int, int]]] = None,
        loops: Optional[LoopBranches] = None,
    ) -> Iterator[ArithmeticOperation]:
        if block_has_dirty_statements(block):
            self.logger.debug(
                "Skipping block %s in %s due to dirty/LLSC/MBE statements",
                hex(block.addr),
                func.name,
            )
            return

        analyzer = IRSBUseDef(block, self.project.arch)
        statements = block.vex.statements
        branch = None
        for tmp_id, op_name, stmt_idx, ins_addr in analyzer.arith_nodes:
            if op_name not in self.target_ops:
                continue
            if min_addr is not None and ins_addr is not None and ins_addr < min_addr:
                continue
            if max_addr is not None and ins_addr is not None and ins_addr > max_addr:
                continue

            if seen is not None:
                key = (func.addr, block.addr, stmt_idx)
                if key in seen:
                    continue
                seen.add(key)
            classification, notes = analyzer.classify_tmp(tmp_id)
            if value_sinks_only and (classification != "value_arith" or not ins_addr):
                continue

            stmt = statements[stmt_idx]
            data = stmt.data
            if loops is not None:
                step = counter_step(data)
                if step and 0 < abs(step[0]) <= MAX_COUNTER_STEP:
                    if branch is None:
                        branch = loops.branch(analyzer, self.project) or ()
                    if branch and is_counter_update(analyzer, stmt_idx, step[1], *branch, self.project):
                        self.loop_counter_skips += 1
                        continue
            if isinstance(data, pyvex.IRExpr.Binop):
                operand0 = self._expr_to_text(data.args[0])
                operand1 = self._expr_to_text(data.args[1])
            elif isinstance(data, pyvex.IRExpr.Unop):
                operand0 = self._expr_to_text(data.args[0])
                operand1 = ""
            else:
                operand0 = ""
                operand1 = ""
            bit_width = data.result_size(block.vex.tyenv)
            operand_states = analyzer.operand_width_states(stmt_idx)
            widen_uses = analyzer.followup_widens(tmp_id)
            yield ArithmeticOperation(
                function=func.name,
                function_addr=func.addr,
                block_addr=block.addr,
                stmt_idx=stmt_idx,
                tmp=tmp_id,
                vex_op=op_name,
                bit_width=bit_width,
                operand0=operand0,
                operand1=operand1,
                ins_addr=ins_addr,
                classification=classification,
                notes=notes,
                operand_states=operand_states,
                widen_uses=widen_uses,
                narrow_use_width=analyzer.narrow_use_width(tmp_id) if classification == "value_arith" else None,
            )

    def _expr_to_text(self, expr) -> str:
        if expr is None:
            return "None"
        if isinstance(expr, pyvex.IRExpr.Const):
            return hex(expr.con.value)
        if isinstance(expr, pyvex.IRExpr.RdTmp):
            return f"t{expr.tmp}"
        if isinstance(expr, pyvex.IRExpr.Get):
            reg_name = self.project.arch.register_names.get(expr.offset, f"reg_{expr.offset}")
            return f"get({reg_name})"
        if isinstance(expr, pyvex.IRExpr.Load):
            addr = self._expr_to_text(expr.addr)
            return f"load[{expr.end}]({addr})"
        if isinstance(expr, pyvex.IRExpr.Binop):
            left = self._expr_to_text(expr.args[0])
            right = self._expr_to_text(expr.args[1])
            return f"{expr.op}({left}, {right})"
        if isinstance(expr, pyvex.IRExpr.Unop):
            inner = self._expr_to_text(expr.args[0])
            return f"{expr.op}({inner})"
        if isinstance(expr, pyvex.IRExpr.Triop):
            parts = ", ".join(self._expr_to_text(arg) for arg in expr.args)
            return f"{expr.op}({parts})"
        if isinstance(expr, pyvex.IRExpr.Qop):
            parts = ", ".join(self._expr_to_text(arg) for arg in expr.args)
            return f"{expr.op}({parts})"
        return expr.__class__.__name__


def build_project(binary_path: str) -> angr.Project:
    project = angr.Project(binary_path, auto_load_libs=False)
    project.analyses.CFGFast(normalize=True, data_references=True)
    return project


def _cli_arguments(argv: Optional[Sequence[str]] = None):
    parser = argparse.ArgumentParser(description="Identify integer arithmetic IR sites.")
    parser.add_argument("binary", help="Path to the binary to analyze.")
    parser.add_argument("--bits", type=int, nargs="+", default=None, help="Bit-widths to match (default: arch width).")
    parser.add_argument(
        "--ops",
        nargs="+",
        default=None,
        help="Restrict to specific operations (e.g. Add Sub Mul Shl).",
    )
    parser.add_argument(
        "--functions",
        nargs="+",
        default=None,
        help="Function names to inspect. Defaults to all discovered functions.",
    )
    parser.add_argument(
        "--function-addrs",
        nargs="+",
        type=_parse_int,
        default=None,
        help="Function addresses to inspect (hex accepted).",
    )
    parser.add_argument("--min-addr", type=_parse_int, default=None, help="Ignore instructions below this address.")
    parser.add_argument("--max-addr", type=_parse_int, default=None, help="Ignore instructions above this address.")
    parser.add_argument("--pretty", action="store_true", help="Verbose output including block/stmt/tmp info.")
    parser.add_argument("--log-level", default="INFO", choices=["DEBUG", "INFO", "WARNING", "ERROR"])
    return parser.parse_args(argv)


def _print_operations(ops: Sequence[ArithmeticOperation], verbose: bool) -> None:
    for op in ops:
        addr = op.ins_addr if op.ins_addr is not None else op.block_addr
        label = op.classification or "unknown"
        if verbose:
            print(
                f"{op.function}@{hex(op.function_addr)} "
                f"-> block {hex(op.block_addr)} stmt {op.stmt_idx} "
                f"{op.vex_op} t{op.tmp} ({op.bit_width} bits) "
                f"@ {hex(addr)} [{label}]: {op.operand0}, {op.operand1}"
            )
            if op.notes:
                note_str = ", ".join(f"{k}={v}" for k, v in sorted(op.notes.items()))
                print(f"    notes: {note_str}")
        else:
            print(f"{label}: {op.vex_op} @ {hex(addr)} in {op.function}")


def main(argv: Optional[Sequence[str]] = None) -> None:
    args = _cli_arguments(argv)
    logging.basicConfig(level=getattr(logging, args.log_level))
    project = build_project(args.binary)
    scanner = IntegerOverflowScanner(project, bit_widths=args.bits, op_names=args.ops)
    operations = scanner.scan(
        function_names=args.functions,
        function_addrs=args.function_addrs,
        min_addr=args.min_addr,
        max_addr=args.max_addr,
    )

    _print_operations(operations, verbose=args.pretty)


if __name__ == "__main__":
    main()
