"""
VEX-level arithmetic operation scanner.

This module mirrors Mango's philosophy of treating interesting IR locations
as sinks.  Instead of well-known libc entry points, the sinks here are the
instructions that perform integer arithmetic which could overflow later.

The scanner walks every IRSB generated by angr, looks for ``WrTmp`` statements
fed by ``Binop`` expressions, and records the contexts of matching operations.
The resulting ``ArithmeticOperation`` objects carry enough metadata
(``block_addr``, ``stmt_idx``, ``tmp``) for the existing RDA pipeline to
resolve their definition/usage chain and eventually feed
``arithmetic_operand_origin``.
"""

